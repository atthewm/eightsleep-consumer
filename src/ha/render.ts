/**
 * Render the Home Assistant YAML that exposes Eight Sleep to Apple Home.
 *
 * Two files come out:
 *
 *   eight_sleep_homekit.yaml  A Home Assistant package: helper sensors that
 *                             HomeKit can use as automation triggers, plus two
 *                             scripts that HomeKit shows as switches.
 *   homekit_bridge.yaml       A `homekit:` block for a dedicated "Eight Sleep"
 *                             HomeKit Bridge that includes only these entities.
 *
 * Strings are written as JSON strings, which are valid double-quoted YAML.
 */

import type { EightSleepEntities, SideEntities } from "./discover.js";

export type TempUnit = "F" | "C";

export interface RenderOptions {
  /** Temperature the Bedtime script sets on every side. */
  bedtimeTemperature: number;
  /** Unit Home Assistant is configured for. Climate entities use HA's unit. */
  unit: TempUnit;
  /** How long the wake-up sensor stays "occupied" after the alarm time. */
  wakeUpMinutes: number;
  /** HomeKit Bridge port. 21064 is HA's default for the first bridge. */
  bridgePort: number;
  bridgeName: string;
  /** Morning window (local hours, [start, end)) for the "Up" sensor. */
  morningStartHour: number;
  morningEndHour: number;
  /** Shown in the file header. */
  generatedAt: string;
}

export const DEFAULT_RENDER_OPTIONS: Omit<RenderOptions, "generatedAt"> = {
  bedtimeTemperature: 68,
  unit: "F",
  wakeUpMinutes: 15,
  bridgePort: 21065,
  bridgeName: "Eight Sleep Bridge",
  morningStartHour: 4,
  morningEndHour: 12,
};

/** Helper entity ids the package creates, derived from their names. */
export function helperIds(side: SideEntities) {
  return {
    wakeUp: `binary_sensor.eight_sleep_${side.slug}_wake_up`,
    upForTheDay: `binary_sensor.eight_sleep_${side.slug}_up_for_the_day`,
  };
}

export const ANYONE_IN_BED_ID = "binary_sensor.eight_sleep_anyone_in_bed";
export const BEDTIME_SCRIPT_ID = "script.eight_sleep_bedtime";
export const ALL_OFF_SCRIPT_ID = "script.eight_sleep_all_off";

const q = (s: string) => JSON.stringify(s);

/** Every climate entity: bed sides and Pod 5 pillows. */
function climates(found: EightSleepEntities): string[] {
  return found.sides.flatMap((s) => [s.climate, s.pillow]).filter((x): x is string => !!x);
}

/** Bed-side climates only. Bedtime leaves pillows on their own schedule. */
function bedClimates(found: EightSleepEntities): string[] {
  return found.sides.map((s) => s.climate).filter((x): x is string => !!x);
}

function validate(found: EightSleepEntities, opts: RenderOptions): void {
  if (found.sides.length === 0) throw new Error("No Eight Sleep sides to render.");
  const [min, max] = opts.unit === "F" ? [55, 110] : [13, 43];
  if (opts.bedtimeTemperature < min || opts.bedtimeTemperature > max) {
    throw new Error(
      `Bedtime temperature ${opts.bedtimeTemperature}°${opts.unit} is outside the Pod range ${min} to ${max}°${opts.unit}.`,
    );
  }
  if (!(opts.morningStartHour >= 0 && opts.morningEndHour <= 24 && opts.morningStartHour < opts.morningEndHour)) {
    throw new Error("Morning window must satisfy 0 <= start < end <= 24.");
  }
}

export function renderPackage(found: EightSleepEntities, opts: RenderOptions): string {
  validate(found, opts);
  const out: string[] = [];
  out.push(
    `# Eight Sleep for Apple Home. Generated by eightsleep-consumer (npm run ha:generate) on ${opts.generatedAt}.`,
    "# Copy to /config/packages/eight_sleep_homekit.yaml. Packages must be enabled in configuration.yaml:",
    "#   homeassistant:",
    "#     packages: !include_dir_named packages",
    "# Needs the Eight Sleep integration from HACS (github.com/lukas-clarke/eight_sleep).",
    "",
    "template:",
  );

  for (const side of found.sides) {
    if (side.nextAlarm) {
      out.push(
        `  # ${side.label}: on at the alarm time from ${side.nextAlarm}, off ${opts.wakeUpMinutes} minutes later.`,
        "  # In Apple Home: \"When <name> detects occupancy\" runs your morning scene.",
        "  - triggers:",
        "      - trigger: time",
        `        at: ${side.nextAlarm}`,
        "    binary_sensor:",
        `      - name: ${q(`Eight Sleep ${side.label} Wake Up`)}`,
        `        unique_id: ${q(`eight_sleep_homekit_${side.slug}_wake_up`)}`,
        "        device_class: occupancy",
        "        icon: mdi:alarm",
        '        state: "true"',
        "        auto_off:",
        `          minutes: ${opts.wakeUpMinutes}`,
      );
    }
    out.push(
      `  # ${side.label}: on when they leave the bed for 10 minutes in the morning window, so snoozing does not count.`,
      "  - triggers:",
      "      - trigger: state",
      `        entity_id: ${side.presence}`,
      '        from: "on"',
      '        to: "off"',
      "        for:",
      "          minutes: 10",
      "    binary_sensor:",
      `      - name: ${q(`Eight Sleep ${side.label} Up For The Day`)}`,
      `        unique_id: ${q(`eight_sleep_homekit_${side.slug}_up_for_the_day`)}`,
      "        device_class: occupancy",
      "        icon: mdi:weather-sunset-up",
      `        state: "{{ ${opts.morningStartHour} <= now().hour < ${opts.morningEndHour} }}"`,
      "        auto_off:",
      "          minutes: 15",
    );
  }

  if (found.sides.length > 1) {
    const checks = found.sides.map((s) => `is_state(${q(s.presence).replace(/"/g, "'")}, 'on')`).join(" or ");
    out.push(
      "  # Anyone on either side of the bed.",
      "  - binary_sensor:",
      `      - name: "Eight Sleep Anyone In Bed"`,
      `        unique_id: "eight_sleep_homekit_anyone_in_bed"`,
      "        device_class: occupancy",
      "        icon: mdi:bed",
      `        state: "{{ ${checks} }}"`,
    );
  }

  const allClimates = climates(found);
  const beds = bedClimates(found);
  if (beds.length > 0) {
    const list = allClimates.map((c) => `          - ${c}`);
    const bedList = beds.map((c) => `          - ${c}`);
    out.push(
      "",
      "script:",
      "  # HomeKit shows scripts as switches. Turning the switch on runs the script once.",
      "  eight_sleep_bedtime:",
      '    alias: "Eight Sleep Bedtime"',
      "    icon: mdi:bed-clock",
      "    mode: single",
      "    variables:",
      `      # Edit this to change the bedtime temperature (°${opts.unit}, Pod range ${opts.unit === "F" ? "55 to 110" : "13 to 43"}).`,
      `      bedtime_temperature: ${opts.bedtimeTemperature}`,
      "    sequence:",
      "      - action: climate.set_hvac_mode",
      "        target:",
      "          entity_id:",
      ...bedList,
      "        data:",
      "          hvac_mode: heat_cool",
      "      - action: climate.set_temperature",
      "        target:",
      "          entity_id:",
      ...bedList,
      "        data:",
      '          temperature: "{{ bedtime_temperature }}"',
      "  # Turns off every side and pillow.",
      "  eight_sleep_all_off:",
      '    alias: "Eight Sleep Off"',
      "    icon: mdi:bed-empty",
      "    mode: single",
      "    sequence:",
      "      - action: climate.turn_off",
      "        target:",
      "          entity_id:",
      ...list,
    );
  }

  return out.join("\n") + "\n";
}

export interface BridgeEntity {
  entityId: string;
  name: string;
}

/** Entities on the Eight Sleep bridge, with the names Apple Home should show. */
export function bridgeEntities(found: EightSleepEntities): BridgeEntity[] {
  const list: BridgeEntity[] = [];
  const add = (entityId: string | undefined, name: string) => {
    if (entityId) list.push({ entityId, name });
  };
  for (const side of found.sides) {
    const ids = helperIds(side);
    const l = side.label;
    add(side.climate, `${l} Bed`);
    add(side.pillow, `${l} Pillow`);
    add(side.presence, `${l} In Bed`);
    add(side.bedTemperature, `${l} Bed Temperature`);
    if (side.nextAlarm) add(ids.wakeUp, `${l} Wake Up`);
    add(ids.upForTheDay, `${l} Up For The Day`);
    add(side.snoozeButton, `${l} Snooze Alarm`);
    add(side.dismissButton, `${l} Dismiss Alarm`);
    side.alarmSwitches.forEach((id, i) => add(id, `${l} Alarm ${i + 1}`));
  }
  if (found.sides.length > 1) add(ANYONE_IN_BED_ID, "Anyone In Bed");
  add(found.roomTemperature, "Eight Sleep Room Temperature");
  add(found.basePreset, "Bed Base Preset");
  if (bedClimates(found).length > 0) {
    add(BEDTIME_SCRIPT_ID, "Eight Sleep Bedtime");
    add(ALL_OFF_SCRIPT_ID, "Eight Sleep Off");
  }
  return list;
}

/** HomeKit names may only use letters, numbers, spaces and a few symbols. */
export function homekitSafeName(name: string): string {
  return name.replace(/[^A-Za-z0-9 '.,-]/g, "").replace(/\s+/g, " ").trim().slice(0, 64) || "Eight Sleep";
}

export function renderBridge(found: EightSleepEntities, opts: RenderOptions): string {
  validate(found, opts);
  const entities = bridgeEntities(found);
  const out: string[] = [
    `# Dedicated HomeKit Bridge for Eight Sleep. Generated by eightsleep-consumer on ${opts.generatedAt}.`,
    "# Paste under the top level of /config/configuration.yaml. If a `homekit:` key already",
    "# exists there, add this list item to it instead of adding a second `homekit:` key.",
    "# After a restart, the pairing QR code is in the Home Assistant notifications.",
    "homekit:",
    `  - name: ${q(opts.bridgeName)}`,
    `    port: ${opts.bridgePort}`,
    "    filter:",
    "      include_entities:",
    ...entities.map((e) => `        - ${e.entityId}`),
    "    entity_config:",
  ];
  for (const e of entities) {
    out.push(`      ${e.entityId}:`, `        name: ${q(homekitSafeName(e.name))}`);
  }
  return out.join("\n") + "\n";
}
